宿命论真正迷人的地方，不在于它解释了世界，而在于它替人解释了失败。一个没能留住的人，一次没能赶上的机会，一段终于走散的关系，只要被归入“命中注定”，疼痛就会显得不那么锋利。我们并不是立刻不难过了，而是终于为难过找到了一个外部秩序。那秩序像一张很大的网，把零散的偶然都收进同一个词里，让混乱有了形状。

